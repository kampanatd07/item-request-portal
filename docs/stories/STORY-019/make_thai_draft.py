def main(taxonomy_path: str, out_path: str) -> None:
    rows = json.load(open(taxonomy_path, encoding="utf-8"))
    wb = Workbook()
    ws = wb.active
    ws.title = "หมวดภาษาไทย (ร่าง)"
    head = ["ระดับ", "รหัส", "ประเภท", "ชื่ออังกฤษ (มาตรฐาน ไม่แก้)", "Name Prefix (ไม่แก้)",
            "ชื่อไทย (ร่าง)", "ตัวอย่าง / คำอธิบาย (ร่าง)",
            "ผลตรวจ", "ชื่อไทยที่แก้", "ตัวอย่างที่แก้", "หมายเหตุผู้ตรวจ"]
    ws.append(head)
    seen: set[str] = set()
    missing: list[str] = []

    def th(key: str) -> tuple[str, str]:
        if key not in TH:
            missing.append(key)
            return ("", "")
        return tuple(unicodedata.normalize("NFC", t) for t in TH[key])  # type: ignore[return-value]

    group_fill = PatternFill("solid", fgColor="E8F3EC")
    for r in rows:
        g = r["group"]
        if g not in seen:
            seen.add(g)
            ws.append(["หมวดหลัก", g, r["product_type"], r["group_name"], "", *th(g)])
            for c in ws[ws.max_row]:
                c.fill = group_fill
                c.font = Font(bold=True)
        key = f"{g}-{r['sub']}"
        ws.append(["หมวดย่อย", key, r["product_type"], r["sub_name"], r["prefix"], *th(key)])
    extra = set(TH) - {f"{r['group']}-{r['sub']}" for r in rows} - seen
    assert not missing and not extra, (missing, extra)

    dv = DataValidation(type="list", formula1='"อนุมัติ,แก้ไข,ไม่แน่ใจ"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"H2:H{ws.max_row}")
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="1F6F43")
        c.alignment = Alignment(wrap_text=True, vertical="center")
    for col, w in zip("ABCDEFGHIJK", [10, 9, 9, 38, 20, 36, 55, 12, 30, 40, 30]):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "D2"
    ws.auto_filter.ref = ws.dimensions

    notes = wb.create_sheet("วิธีตรวจ")
    for line in [
        "ร่างคำแปลหมวดสินค้าเป็นภาษาไทย สำหรับ STORY-019 (ร่างโดย Claude 2026-11-11 ยังไม่อนุมัติ)",
        "ชื่อไทยและตัวอย่างใช้แสดงบนหน้าจอให้ผู้ขอเข้าใจเท่านั้น ไม่เปลี่ยนรหัส ชื่ออังกฤษ Name Prefix หรือไฟล์ export",
        "ช่อง 'ผลตรวจ': อนุมัติ = ใช้ตามร่าง / แก้ไข = ใส่คำที่ถูกในช่อง 'ชื่อไทยที่แก้' หรือ 'ตัวอย่างที่แก้' / ไม่แน่ใจ = เขียนเหตุผลในหมายเหตุ",
        "ตัวอย่างควรเป็นของที่โรงงานซื้อจริง ถ้าตัวอย่างไหนทำให้เลือกหมวดผิดได้ ขอให้แก้หรือลบ",
        "หมวด 99 'อื่นๆ' ควรใช้ให้น้อยที่สุด",
        "ชื่อไทยไม่ควรยาวเกิน 40 ตัวอักษร เพื่อให้แสดงใน dropdown ได้",
    ]:
        notes.append([line])
    notes.column_dimensions["A"].width = 120
    wb.save(out_path)
    print(f"{len(rows)} sub-categories, {len(seen)} groups -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
