# "ขอแทน: <name>" on its own line of a `submitted` event. Anchored to the line
# start, never \b next to Thai (HANDOFF §6.1). The rest of the line is the name
# exactly as typed ("<", ">" included); a trailing CR (CRLF) is dropped. Only a
# trailing " <...@...>" — the email this feature appends — is removed, so a
# downgrade + upgrade after use does not glue the email onto the name.
_ON_BEHALF = re.compile(r"^ขอแทน:[ \t]*(?P<name>[^\r\n]*)\r?$", re.MULTILINE)
_TRAILING_EMAIL = re.compile(r"[ \t]*<[^<>@\s]+@[^<>@\s]+>[ \t]*$")


def _clean_thai(text: str) -> str:
    """NFC, then recompose SARA AM — never NFKC (HANDOFF §6.2). Self-contained
    copy of snapshots.fix_thai: a migration must not import app code."""
    text = unicodedata.normalize("NFC", text).replace("\u0e4d\u0e32", "\u0e33")
    return " ".join(text.split())


def _backfill_names() -> None:
    """Fill originator_name from the 'ขอแทน:' line written before this column existed."""
    bind = op.get_bind()
    rows = bind.execute(sa.text(
        "SELECT request_id, detail FROM request_events "
        "WHERE action = 'submitted' AND detail LIKE '%ขอแทน:%' ORDER BY at, id"))
    names: dict[int, str] = {}
    for request_id, detail in rows:
        m = _ON_BEHALF.search(detail or "")
        if m and request_id not in names:
            name = _clean_thai(_TRAILING_EMAIL.sub("", m.group("name")))
            if name:
                names[request_id] = name[:100]
    for request_id, name in names.items():
        bind.execute(sa.text(
            "UPDATE item_requests SET originator_name = :name "
            "WHERE id = :id AND originator_name IS NULL"), {"name": name, "id": request_id})
    # ASCII only: a Windows console (cp1252) cannot print Thai and would fail
    # the whole migration.
    print(f"originator backfill: {len(names)} names from on-behalf events")


# Kept in step with app.services.notify (a migration must not import app code).
NOT_APPLICABLE = "notify_not_applicable"
NOT_APPLICABLE_DETAIL = "เกิดก่อนมีระบบแจ้งเตือนทางอีเมล"
_STATUS_ACTIONS = ("submitted", "in_review", "needs_info", "approved", "rejected",
                   "exported", "created")


def _close_pre_existing() -> None:
    """Record that nothing was ever owed for what happened before email existed.

    Without this the resend list would show every request already `created`
    and every current needs_info/rejected change as a lost email, and "send
    all" would email people about months-old decisions. An honest
    `notify_not_applicable` event (never a fake `notified`) closes each one;
    the request's status is left as it is. Only current changes are closed —
    a superseded change is never listed anyway (Peter, 2026-10-08).
    """
    bind = op.get_bind()
    statuses = ", ".join(f"'{a}'" for a in _STATUS_ACTIONS)
    # The latest status change of each request (by event id).
    latest = {request_id: (event_id, action) for request_id, event_id, action in bind.execute(
        sa.text(f"SELECT e.request_id, e.id, e.action FROM request_events e "
                f"WHERE e.action IN ({statuses}) AND e.id = ("
                f"  SELECT max(l.id) FROM request_events l "
                f"  WHERE l.request_id = e.request_id AND l.action IN ({statuses}))"))}
    closes: list[tuple[int, int | None]] = []
    for request_id, status in bind.execute(sa.text(
            "SELECT id, status FROM item_requests "
            "WHERE status IN ('created', 'needs_info', 'rejected') ORDER BY id")):
        event_id, action = latest.get(request_id, (None, None))
        if status == "created":
            # A request older than the event log has no 'created' event: ref stays empty.
            closes.append((request_id, event_id if action == "created" else None))
        elif action == status:
            closes.append((request_id, event_id))
        # needs_info/rejected with no matching change event: nothing to announce.
    for request_id, ref in closes:
        bind.execute(sa.text(
            "INSERT INTO request_events (request_id, actor, action, detail, ref_event_id) "
            "VALUES (:r, 'system', :a, :d, :ref)"),  # at: the column default, as the app
            {"r": request_id, "a": NOT_APPLICABLE, "d": NOT_APPLICABLE_DETAIL, "ref": ref})
    print(f"notifications closed as not applicable: {len(closes)}")  # ASCII only, see above


